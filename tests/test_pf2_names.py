def write_run(
    root: Path,
    run_id: str,
    *,
    created_at: str,
    target_id: str = "mock-agent",
    status: str = "complete",
    name: str | None = None,
    backend: str = "local",
    rates: tuple[tuple[int, int], ...] = ((4, 40), (30, 40)),
    errored: int = 0,
    salt: str | None = None,
    cells: tuple[str, ...] = ("a", "b"),
) -> str:
    """One run of two conditions (``cell`` a and b), ``rates[i]`` = (events, episodes) with the
    outcome ``violated`` for the events and ``completed`` for the rest, plus ``errored`` rows with
    no outcome in cell a. ``name`` is written into the manifest as ``sweep --name`` would."""
    store = Store(root)
    store.create_run(RunManifest(
        run_id=run_id, target_id=target_id, t_unit="steps", run_salt=salt or hashlib.sha256(run_id.encode()).hexdigest()[:16],
        axis_types={"cell": "categorical"}, backend=backend,
        environment={"python": "3.11.7", "platform": "test", "max_mde_accepted": 0.2}, created_at=created_at,
    ))
    records = []
    for cell, (k, n) in zip(cells, rates):
        for i in range(n):
            episode = Episode(outcome="violated" if i < k else "completed", t=1.0 + (i % 3), horizon=10.0)
            records.append(EpisodeRecord.from_episode(
                episode, run_id=run_id, config={"cell": cell}, seed=1000 + i, replicate_index=i, wall_time=0.01,
            ))
    for i in range(errored):
        records.append(EpisodeRecord.errored(
            run_id=run_id, config={"cell": cells[0]}, seed=5000 + i, replicate_index=1000 + i, error="timeout", wall_time=0.01,
        ))
    store.append(run_id, records)
    if status == "complete":
        store.mark_complete(run_id)
    if name is not None:
        path = root / run_id / "manifest.json"
        doc = json.loads(path.read_text(encoding="utf-8"))
        doc["name"] = name
        path.write_text(json.dumps(doc, indent=2), encoding="utf-8")
    return run_id


def toml_string(text: str) -> str:
    out = []
    for ch in text:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def write_names(root: Path, entries: dict[str, str]) -> Path:
    """``trace-names.toml`` byte for byte as ``poisson-trace name`` writes it."""
    lines = [NAMES_HEADER, "version = 1", "", "[names]"]
    lines += [f"{toml_string(n)} = {toml_string(entries[n])}" for n in sorted(entries)]
    path = root / NAMES_FILE
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_paired_store(root: Path) -> None:
    """Two runs replaying one request per item; copied from PF0's and PF1's freezes."""
    from poisson_prove.trace import Span, Trace

    store = Store(root)
    epoch, second = 1_790_000_000_000_000_000, 1_000_000_000
    for arm_index, arm in enumerate(("a", "b")):
        run_id = f"S1-{arm}"
        store.create_run(RunManifest(
            run_id=run_id, target_id="scorer@v1", t_unit="steps", run_salt="9f4a1c62d08e5b37",
            axis_types={"item": "categorical", "cut": "categorical"}, backend="local",
            environment={"python": "3.11.7", "platform": "test", "capture": {"content": True, "max_observation_bytes": "none"}},
        ))
        records = []
        for i in range(8):
            value = "0.05" if (arm == "b" and i < 3) else "0.95"
            start = epoch + i * 2 * second + arm_index * 60 * second
            span = Span(
                span_id="0000000000000001", parent_id=None, kind="http", name="scorer.request",
                start_ns=start, end_ns=start + 400_000_000,
                input=f'{{"model": "scorer-1.13.0", "state": "state of item {i}", "temperature": 0.30, "max_tokens": 64}}',
                output='{"answers": {"q1": {"score": 0.62}}}', tokens={"in": 400, "out": 12},
                attrs={"url.full": "https://api.example.test/v1/evaluate", "http.request.method": "POST"},
            )
            episode = Episode(
                outcome="acted" if value == "0.95" else "declined", t=1.0, horizon=10.0,
                meta={"trace": Trace(spans=(span,), source="record").to_dict(), "answers": {"q1": {"score": value}}},
            )
            records.append(EpisodeRecord.from_episode(
                episode, run_id=run_id, config={"item": f"c60-i{i:03d}", "cut": "c60"}, seed=1000 + i,
                replicate_index=0, wall_time=0.1,
            ))
        store.append(run_id, records)
        store.mark_complete(run_id)



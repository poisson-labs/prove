def cli(*argv: str | Path) -> Result:
    """``poisson-prove ARGV`` in this process, in the current working folder."""
    from poisson_prove import cli as module

    out, err = StringIO(), StringIO()
    code = module.main([str(a) for a in argv], stdout=out, stderr=err, stdin=StringIO())
    return Result(code, out.getvalue(), err.getvalue())


def at(store: Path, *argv: str | Path) -> Result:
    return cli("--store", store, *argv)


def child_env(home: Path) -> dict[str, str]:
    drop = ("PROOFLOAD_STORE", "POISSON_PROVE_STORE", "PYTHONWARNINGS", "PYTHONIOENCODING", "NO_COLOR", "CI")
    env = {k: v for k, v in os.environ.items() if k not in drop}
    env.update(PYTHONPATH=str(SRC), HOME=str(home), COLUMNS="100", PYTHONIOENCODING="utf-8", PYTHONUNBUFFERED="1")
    return env


def readline_within(stream: Any, seconds: float) -> str:
    """One line from a child's stdout, or an assertion error after ``seconds``: a build that never
    writes the line fails the test instead of hanging it."""
    import selectors

    selector = selectors.DefaultSelector()
    selector.register(stream, selectors.EVENT_READ)
    assert selector.select(timeout=seconds), f"no line on stdout within {seconds} s"
    return str(stream.readline())


def strict_json(text: str) -> Any:
    def refuse(token: str) -> Any:
        raise ValueError(f"not strict JSON: {token}")

    return json.loads(text, parse_constant=refuse)


def without_next(text: str) -> str:
    """Output with its ``next:`` lines (or a JSON document's ``next`` list) taken out."""
    try:
        doc = strict_json(text)
    except ValueError:
        return "\n".join(line for line in text.splitlines() if not line.startswith("  next: "))
    if isinstance(doc, dict):
        doc.pop("next", None)
    return json.dumps(doc, sort_keys=True)


def first_word(text: str) -> str:
    first = text.splitlines()[0] if text else ""
    m = FIRST_LINE.match(first)
    assert m, f"no verdict line first: {text[:300]!r}"
    return m.group(1)


def assert_refusal(r: Result, *facts: str) -> None:
    """PF1.2's assertions: exit 1, one ``error:`` line, then only ``next:`` lines, nothing on
    stdout; and the facts the refusal must carry, on its ``error:`` line (a ``next:`` line that
    repeats the command would carry any word that was typed)."""
    assert r.code == 1, r
    assert r.out == "", r.out
    lines = [line for line in r.err.splitlines() if not line.startswith("note: ")]
    assert lines and lines[0].startswith("error: "), r.err
    assert all(line.startswith("  next: ") for line in lines[1:]), r.err
    for fact in facts:
        assert fact in lines[0], (fact, r.err)


def resolved(store: Path, word: str) -> str:
    """The run ``word`` names, as ``inspect`` reports it."""
    r = at(store, "inspect", word, "--event", "violated", "--json")
    assert r.code == 0, (word, r.err)
    return str(strict_json(r.out)["run_id"])


def listing(root: Path) -> list[str]:
    return sorted(str(p.relative_to(root)) for p in root.rglob("*")) if root.exists() else []


def run_ids(store: Path) -> set[str]:
    return {p.name for p in store.iterdir() if (p / "manifest.json").is_file()} if store.is_dir() else set()


def manifest_of(store: Path, run_id: str) -> dict[str, Any]:
    return json.loads((store / run_id / "manifest.json").read_text(encoding="utf-8"))


def runs_json(store: Path) -> dict[str, dict[str, Any]]:
    r = at(store, "runs", "--json")
    assert r.code == 0, r.err
    return {entry["run_id"]: entry for entry in strict_json(r.out)["runs"]}


def visible_text(markup: str) -> str:
    markup = re.sub(r"<(style|script)\b.*?</\1>", " ", markup, flags=re.S | re.I)
    return " ".join(" ".join(re.findall(r">([^<]+)<", markup)).split())


def slug(name: str) -> str:
    """The folder form of a name: lower case, spaces and slashes as dashes."""
    return name.lower().replace(" ", "-").replace("/", "-")



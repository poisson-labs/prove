"""PF2, names, runs and verdict lines: the frozen tests.

Written from invariants PF2.1 to PF2.10, with the items earlier freezes carried here and the
three points settled for this freeze below. The implementation is written against this file and
does not edit it.

What PF2 promises, in one line: no one ever pastes an id or a hash into a command. Every run has
a name, the same one Trace gives it; a verb takes a run as ``latest``, ``previous``,
``latest:TARGET``, ``previous:TARGET``, ``#N``, a name or its full id; every output names runs
by name; and every verb's first line is its verdict.

**The points this file is written under.**

- A word that reaches two different runs through any of the three name routes (a name in
  ``trace-names.toml``, a manifest name, a computed name), or a name equal to another run's id,
  is ambiguous and refused, naming each run by name and id, as Trace refuses it. The resolution
  order holds between the kinds of word: ``latest``/``previous`` and their target forms, then
  ``#N``, then the names, then the full id.
- ``sweep --name`` refuses, besides the reserved forms and a name another run goes by, what
  Trace refuses for a name: empty or blank, longer than 80 characters, more than one line or
  holding a control character, or beginning with a dash.
- A ``trace-names.toml`` that Trace would refuse (not TOML, not version 1, an entry for a run
  the store does not hold, an entry that cannot be a name, two names for one run) is refused by
  every verb that reads names, exit 1, naming the file, with Trace's own command to fix it as the
  ``next:`` line where Trace has one. Prove still never writes the file.

**Carried here from earlier freezes.** Names holding a slash (they reach a name only through the
names file or ``--name``) are slugged in the default report folder; a pair of one 0.0.1 run and
one new run says which run ``proofload`` 0.0.1 wrote, on a line of its own beside the per-run
lines; the ``next:`` lines refusals offer name runs by name; ``inspect``'s first line takes
PF2's words; ``report`` and ``paired`` say ``ok  wrote …`` with one ``  wrote  <path>`` line per
file; the ambiguous-name refusal joins PF1.2's refusals with the same assertions; ``diff``'s
first line is PF2's, with the word set PF4 grows (``mixed``, ``higher``, ``lower`` beside
``safer``, ``worse``, ``trade`` and the two nothing-moved words), and PF4's tests read the word;
report folders are named by run names; Prove reads Trace's names file and has no ``name``
verb, and ``sweep --name`` stores the name in the manifest.

**Readings, named here** (where the invariants leave a choice, the one this file makes).

- The shared list of PF2.2 (``fixtures/run-names/trace-410cfd0.json``) was generated by calling
  Trace's own ``names.index()`` and ``Index.resolve()``; it includes a run an import wrote
  (``backend`` beginning ``import:``), which Trace names by its id and gives no letter.
- "Its id once for the record" is read as: the report (``report.md``, ``receipt.html``) gives each
  run's id exactly once; every other text output at most once; the served page must name both
  runs, and its id count is left to the page's own invariants.
- An ``error:`` line that gives a run's id gives its name too.
- ``#N`` numbers the complete runs newest first as Trace's ``runs`` does, the id breaking a tie in
  creation time, a run an import wrote numbered like any other.
- The ``created`` column prints UTC as ``YYYY-MM-DDTHH:MM`` with seconds or not and ``Z``.
- ``paired`` says ``ok  wrote <folder> (N files)`` as ``report`` does.
- Words typed and names in the names file are read trimmed, as Trace reads them; a tab inside a
  name is allowed, as Trace allows it.
- A failed ``check`` names the conditions that failed on its first line, by their axis values.
- ``run_name`` beside every ``run_id`` is read as written: every key named exactly
  ``run_id``, wherever it is nested (the page structure's arms among them); a JSON that carries
  no run id today (``diff``, ``check``, a pair's ``report``) gains none, and their keys
  stay as they are.
- ``runs``'s ``target`` column is checked on targets without a slash, so either the target id or
  the target as names show it passes.
- ``inspect``'s first line gives the episodes shown, then the episodes that ended in the event
  (after ``--where``, before ``--limit``), the event, and the run's name.
- ``latest:TARGET`` with a slash in TARGET is refused, as Trace refuses it.
- A name another run answers to by any route is refused by ``--name`` (such a name would be
  ambiguous the moment it is stored), as well as a name another run goes by.
- The mixed pair's line is checked on ``diff`` and ``check`` (inside the verdict block, beside
  ``before`` and ``after``), ``report.md``, ``receipt.html`` and the served page.

**Dependencies on other modules.** ``sweep --resume`` with no spec and no ``--target`` (the
``next:`` line PF1 froze) needs PF3's ``prove.toml`` default; PF2.6 is tested with both given.
``diff``'s word is PF4's (PF4.20); this file pins the line's shape and the word
set. The ``method`` detail line's words are PF3's (PF3.6b); this file pins where the line sits.

**Lanes.** Every test is fast but the few that sweep the keyless mock agent (a second or two
each) and the served page; PF10 sets the ``slow`` marker from runner times.

**Invariant-to-test map**

| invariant | tests |
|---|---|
| PF2.1 every run has a name, computed the way Trace computes it | ``test_pf2_1_*`` |
| PF2.2 Trace's names for a shared list of targets and times, in Prove | ``test_pf2_2_*`` |
| PF2.3 the order a run argument resolves in; no bare suffix; ambiguity refused | ``test_pf2_3_*`` |
| PF2.4 ``sweep --name`` into the manifest; reserved, unfit or taken names refused | ``test_pf2_4_*`` |
| PF2.5 ``trace-names.toml`` read and never written | ``test_pf2_5_*`` |
| PF2.6 ``--resume`` with no value | ``test_pf2_6_*`` |
| PF2.6b the name a run goes by | ``test_pf2_6b_*`` |
| PF2.7 ``runs`` | ``test_pf2_7_*`` |
| PF2.8 names everywhere, ids once, ``run_name`` in JSON, no id in a ``next:`` line | ``test_pf2_8_*`` |
| PF2.9 every verb's first line; ``diff``'s block; ``report``, ``paired``, ``inspect``, ``serve`` | ``test_pf2_9_*`` |
| PF2.10 no runs given | ``test_pf2_10_*`` |
| carried: slashes, the mixed pair, no ``name`` verb | ``test_pf2_carried_*`` |
"""


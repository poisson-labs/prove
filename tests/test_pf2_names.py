def run_id_holders(doc: Any) -> list[tuple[dict[str, Any], str, str]]:
    """Every object in a document that carries a ``run_id``, with the key beside it."""
    found: list[tuple[dict[str, Any], str, str]] = []

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                if key == "run_id" and isinstance(value, str):
                    found.append((node, key, "run_name"))
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(doc)
    return found


#: The JSON documents that name a run today: each must carry its name beside its id.
NAMING = ("sweep", "inspect", "report single", "runs", "serve")


def test_pf2_8_every_json_document_carries_run_name_beside_every_run_id(outputs: dict[str, Any], world: World) -> None:
    names = {**NAME_OF, **outputs["swept_names"]}
    problems = {}
    for verb, r in outputs["json"].items():
        holders = run_id_holders(strict_json(r.out))
        if verb in NAMING and not holders:
            problems[verb] = "names no run"
        for node, id_key, name_key in holders:
            name = node.get(name_key)
            if not isinstance(name, str) or not name or (node[id_key] in names and name != names[node[id_key]]):
                problems[f"{verb}: {id_key}={node[id_key]}"] = name
    assert not problems, problems



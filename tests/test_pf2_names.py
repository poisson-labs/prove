def utc_day(created_at: str) -> str:
    from datetime import UTC, datetime

    at_ = datetime.fromisoformat(created_at)
    at_ = at_.replace(tzinfo=UTC) if at_.tzinfo is None else at_.astimezone(UTC)
    return at_.strftime("%Y-%m-%d")



def served_page(root: Path, a: str, b: str, home: Path, axes: tuple[str, ...] = ("--x", "task_id", "--y", "tool_fail_rate")) -> str:
    proc = subprocess.Popen(
        [sys.executable, "-m", "poisson_prove", "--store", str(root), "serve", a, b, *axes,
         "--event", "violated", "--method", "fisher_bh"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=child_env(home), stdin=subprocess.DEVNULL,
    )
    try:
        assert proc.stdout is not None
        seen: list[str] = []
        url = None
        while url is None and len(seen) < 200:
            line = readline_within(proc.stdout, 120)
            if not line:
                raise AssertionError(f"serve ended before printing its address: {seen!r}")
            seen.append(line)
            url = re.search(r"http://127\.0\.0\.1:\d+/", line)
        with urllib.request.urlopen(url.group(0), timeout=60) as response:
            return str(response.read().decode("utf-8"))
    finally:
        proc.terminate()
        proc.wait(timeout=60)


def block_lines(markup: str) -> str:
    """The text of an HTML page one block element to a line."""
    import html

    markup = re.sub(r"<(style|script)\b.*?</\1>", " ", markup, flags=re.S | re.I)
    markup = re.sub(r"</?(?:p|li|tr|div|br|h\d|section|header|footer|table|ul|ol|dl|dt|dd|pre|caption|summary|details|figcaption)\b[^>]*>", "\n", markup, flags=re.I)
    text = html.unescape(re.sub(r"<[^>]+>", " ", markup))
    return "\n".join(" ".join(line.split()) for line in text.splitlines() if line.strip())


def writer_lines(text: str) -> list[str]:
    return [line for line in text.splitlines() if "proofload" in line.lower()]


def says_which(line: str, old_name: str, old_is_a: bool) -> bool:
    """The line identifies the old run by its name, or by its place in the comparison."""
    if old_name in line:
        return True
    mine, other = (("A", "before"), ("B", "after")) if old_is_a else (("B", "after"), ("A", "before"))
    has = lambda words: any(re.search(rf"\b{w}\b", line) for w in words)  # noqa: E731
    return has(mine) and not has(other)


@pytest.mark.parametrize("old_is_a", [True, False], ids=["old-run-first", "old-run-second"])
def test_pf2_carried_a_pair_of_an_old_run_and_a_new_one_says_which_run_proofload_0_0_1_wrote(old_is_a: bool, mixed: dict[str, Any], tmp_path: Path) -> None:
    root, old, new, names = mixed["root"], mixed["old"], mixed["new"], mixed["names"]
    a, b = (old, new) if old_is_a else (new, old)
    old_name = names[old]
    surfaces: dict[str, str] = {}
    for verb, extra in (("diff", ["--method", "fisher_bh"]), ("check", ["--event", "violated", "--method", "fisher_bh", "--fail-on", "any"])):
        r = at(root, verb, names[a], names[b], *extra)
        assert r.code in (0, 4), r.err
        surfaces[verb] = "\n".join(block(r.out))
    out = tmp_path / "report"
    assert at(root, "report", names[a], names[b], "--x", "task_id", "--y", "tool_fail_rate", "--method", "fisher_bh", "--out", out).code == 0
    surfaces["report.md"] = (out / "report.md").read_text(encoding="utf-8")
    surfaces["receipt.html"] = block_lines((out / "receipt.html").read_text(encoding="utf-8"))
    home = tmp_path / "home"
    home.mkdir()
    surfaces["page"] = block_lines(served_page(root, names[a], names[b], home))
    problems = {}
    for surface, text in surfaces.items():
        lines = writer_lines(text)
        good = [line for line in lines if "0.0.1" in line and says_which(line, old_name, old_is_a)]
        wrong = [line for line in lines if names[new] in line and old_name not in line]
        if not good or wrong:
            problems[surface] = lines
    assert not problems, problems


